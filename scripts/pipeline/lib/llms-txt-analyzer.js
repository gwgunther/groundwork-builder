/**
 * llms.txt analyzer — HTTP fetch + content quality checks.
 *
 * Lighthouse can report "llms.txt does not follow recommendations" while the
 * file still returns HTTP 200. Always fetch the file directly; never infer
 * presence from Lighthouse alone.
 *
 * Export:
 *   auditLlmsTxt(siteUrl) → { status, url, httpStatus, content, issues, ... }
 */

const FETCH_TIMEOUT_MS = 12_000;
const EXCERPT_MAX_LINES = 24;

/**
 * @param {string} siteUrl
 * @returns {Promise<object>}
 */
export async function auditLlmsTxt(siteUrl) {
  const base = normalizeSiteUrl(siteUrl);
  const llmsUrl = `${base}/llms.txt`;
  const fetched = await fetchLlmsTxt(llmsUrl);

  if (!fetched.ok || !fetched.content?.trim()) {
    return {
      status: 'absent',
      url: llmsUrl,
      httpStatus: fetched.status,
      content: null,
      excerpt: null,
      issues: ['No llms.txt file at the domain root (HTTP ' + (fetched.status ?? 'error') + ').'],
      flaggedLines: [],
      generator: null,
      lineCount: 0,
      linkCount: 0,
    };
  }

  const analysis = analyzeLlmsTxtContent(fetched.content, llmsUrl);
  return {
    ...analysis,
    url: llmsUrl,
    httpStatus: fetched.status,
    content: fetched.content,
  };
}

/**
 * @param {string} llmsUrl
 */
async function fetchLlmsTxt(llmsUrl) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), FETCH_TIMEOUT_MS);
  try {
    const res = await fetch(llmsUrl, {
      signal: controller.signal,
      headers: { Accept: 'text/plain,text/markdown,*/*' },
      redirect: 'follow',
    });
    const content = res.ok ? await res.text() : '';
    return { ok: res.ok, status: res.status, content };
  } catch (err) {
    return { ok: false, status: null, content: '', error: err.message };
  } finally {
    clearTimeout(timer);
  }
}

/**
 * @param {string} content
 * @param {string} llmsUrl
 */
export function analyzeLlmsTxtContent(content, llmsUrl = '') {
  const lines = content.split(/\r?\n/);
  const issues = [];
  const flaggedLines = [];
  const lower = content.toLowerCase();

  const h1 = lines.find(l => /^#\s+/.test(l));
  const h1Text = h1 ? h1.replace(/^#\s+/, '').trim() : null;
  const hasBlockquote = lines.some(l => /^>\s+/.test(l));
  const linkCount = (content.match(/\[[^\]]+\]\([^)]+\)/g) || []).length;
  const generator = detectGenerator(content);

  if (!h1) {
    issues.push('Missing H1 heading (# Practice Name).');
  } else if (h1Text.length > 60 || /welcome to/i.test(h1Text) || h1Text.includes(':')) {
    issues.push('H1 is verbose or marketing-heavy instead of a clean practice name.');
    flaggedLines.push({ line: h1.trim(), reason: 'Should be a short practice name, not a welcome headline.' });
  }

  if (!hasBlockquote) {
    issues.push('Missing summary blockquote (> one-line description of the practice).');
  }

  if (linkCount < 3) {
    issues.push(`Only ${linkCount} markdown link(s) — agents need linked key pages and services.`);
  }

  if (!/^##\s+services/m.test(content) && !/^##\s+key pages/m.test(content)) {
    issues.push('No Services or Key pages section — agents cannot see what you offer.');
  }

  if (/^##\s+popups/m.test(lower) || /post_type=popup/i.test(content)) {
    issues.push('Lists CMS popup pages — noise that misleads AI assistants.');
    for (const line of lines) {
      if (/popup/i.test(line) || /post_type=popup/i.test(line)) {
        flaggedLines.push({ line: line.trim(), reason: 'Popup/internal CMS URL — not useful for AI discovery.' });
      }
    }
  }

  if (/carnival cruise|ensenada/i.test(content)) {
    issues.push('Includes off-topic promotional pages unrelated to dental care.');
    for (const line of lines) {
      if (/carnival cruise|ensenada/i.test(line)) {
        flaggedLines.push({ line: line.trim(), reason: 'Off-topic promotion — dilutes what AI agents learn about the practice.' });
      }
    }
  }

  if (generator === 'yoast') {
    issues.push('Auto-generated by Yoast SEO — typically a CMS dump, not a curated agent summary.');
    const genLine = lines.find(l => /generated by yoast/i.test(l));
    if (genLine) flaggedLines.push({ line: genLine.trim(), reason: 'Plugin boilerplate, not practice-authored content.' });
  }

  if (content.trim().length < 200) {
    issues.push('File is too short to be a useful machine-readable summary.');
  }

  const excerpt = lines.slice(0, EXCERPT_MAX_LINES).join('\n')
    + (lines.length > EXCERPT_MAX_LINES ? `\n… (${lines.length - EXCERPT_MAX_LINES} more lines)` : '');

  const status = issues.length === 0 ? 'good' : 'poor';

  return {
    status,
    excerpt,
    issues,
    flaggedLines: flaggedLines.slice(0, 8),
    generator,
    lineCount: lines.length,
    linkCount,
    verifyUrl: llmsUrl,
  };
}

/**
 * Merge HTTP analysis with Lighthouse llms audit scores.
 *
 * @param {object} httpAudit - from auditLlmsTxt()
 * @param {object} lighthouseMeta - from parseLighthouseReport()
 * @returns {'absent'|'poor'|'good'|null}
 */
export function resolveLlmsTxtStatus(httpAudit, lighthouseMeta = {}) {
  if (!httpAudit) return null;
  if (httpAudit.status === 'absent') return 'absent';

  const lhAudits = lighthouseMeta.audits || {};
  const qualityAudit = lhAudits['llms-txt'] || lhAudits['llms-txt-present'];
  const lighthouseSaysPoor = qualityAudit?.score != null && qualityAudit.score < 1;

  if (httpAudit.status === 'poor' || lighthouseSaysPoor) return 'poor';
  if (httpAudit.status === 'good' && !lighthouseSaysPoor) return 'good';
  return 'poor';
}

function detectGenerator(content) {
  if (/generated by yoast seo/i.test(content)) return 'yoast';
  return null;
}

function normalizeSiteUrl(url) {
  try {
    const u = new URL(url);
    return `${u.protocol}//${u.host}`;
  } catch {
    return String(url).replace(/\/$/, '');
  }
}
